var DICTIONNAIRE: { [key in Langue]: { [cle: string]: string } } = { fr: FR, en: EN }

var CtxLangue = createContext<{ langue: Langue; changer: (l: Langue) => void }>({ langue: 'fr', changer: function () {} })

// Langue courante lisible hors de React (tables de libelles d'enums). Un
// changement de langue re-rend tout l'arbre via le contexte, ce qui rafraichit
// aussi les libelles derives.
var _langueCourante: Langue = (function () {
  try { return (localStorage.getItem('ebiosrm_langue') as Langue) || 'fr' } catch (e) { return 'fr' }
})()

export function langueCourante(): Langue { return _langueCourante }

export function traduire(cle: string): string {
  return DICTIONNAIRE[_langueCourante][cle] || FR[cle] || cle
}

export function ProviderLangue(props: { children: React.ReactNode }) {
  var [langue, setLangue] = useState<Langue>(_langueCourante)

  function changer(l: Langue) {
    try { localStorage.setItem('ebiosrm_langue', l) } catch (e) { /* prive */ }
    _langueCourante = l
    setLangue(l)
  }

  useEffect(function () {
    document.documentElement.lang = langue
    _langueCourante = langue
  }, [langue])

  return <CtxLangue.Provider value={{ langue: langue, changer: changer }}>{props.children}</CtxLangue.Provider>
}

export function useLangue() {
  return useContext(CtxLangue)
}

export function useT(): (cle: string) => string {
  var langue = useContext(CtxLangue).langue
  return function (cle: string) {
    return DICTIONNAIRE[langue][cle] || FR[cle] || cle
  }
}
